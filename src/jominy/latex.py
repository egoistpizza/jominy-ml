"""Writing figures, booktabs tables and number macros."""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
from matplotlib.figure import Figure

from jominy.evaluate import Interval


def num(x: float, digits: int = 1) -> str:
    """Number formatted for siunitx ``\\num{}`` (decimal point; siunitx prints the comma)."""
    text = f"{x:.{digits}f}"
    return text[1:] if text.startswith("-") and float(text) == 0 else text


class Outputs:
    """Single place through which every generated artefact passes.

    With a ``root`` directory the artefacts are written to disk. Without one they are
    kept in memory (``files`` and ``macros``), which lets tests run the pipeline
    without touching the file system.
    """

    def __init__(self, root: Path | None = None) -> None:
        self.root = root
        if root is not None:
            root.mkdir(parents=True, exist_ok=True)
        self.files: dict[str, str] = {}
        self.macros: dict[str, str] = {}

    def figure(self, name: str, fig: Figure) -> None:
        if self.root is not None:
            fig.savefig(self.root / f"{name}.pdf", metadata={"CreationDate": None})
        self.files[f"{name}.pdf"] = ""
        plt.close(fig)

    def csv(self, name: str, df: pd.DataFrame) -> None:
        self._store(f"{name}.csv", df.to_csv())

    def table(
        self, name: str, colspec: str, header: Sequence[str], rows: Iterable[Sequence[str]]
    ) -> None:
        lines = [
            rf"\begin{{tabular}}{{@{{}}{colspec}@{{}}}}",
            r"\toprule",
            " & ".join(header) + r" \\",
            r"\midrule",
        ]
        lines += [" & ".join(r) + r" \\" for r in rows]
        lines += [r"\bottomrule", r"\end{tabular}"]
        self._store(f"{name}.tex", "\n".join(lines) + "\n")

    def macro(self, name: str, value: str) -> None:
        if not name.isalpha():
            raise ValueError(f"LaTeX macro names may only contain letters: {name!r}")
        if name in self.macros:
            raise ValueError(f"macro \\{name} defined twice")
        self.macros[name] = value

    def interval(self, name: str, iv: Interval, digits: int = 1) -> None:
        """Macros ``name``, ``nameLow`` and ``nameHigh`` for an estimate with its interval."""
        self.macro(name, num(iv.estimate, digits))
        self.macro(f"{name}Low", num(iv.low, digits))
        self.macro(f"{name}High", num(iv.high, digits))

    def write_macros(self) -> None:
        lines = ["% Generated by jominy.pipeline - do not edit."]
        lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in sorted(self.macros.items())]
        self._store("results.tex", "\n".join(lines) + "\n")

    def _store(self, filename: str, text: str) -> None:
        self.files[filename] = text
        if self.root is not None:
            (self.root / filename).write_text(text, encoding="utf-8")
